-- SMARTSHELF PostgreSQL schema
-- PostgreSQL 16+
-- Stock source of truth: batch_inventory.quantity
-- Expiration dates belong to batches, not products.

BEGIN;

CREATE TABLE IF NOT EXISTS categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE,
    description TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS suppliers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(160) NOT NULL,
    contact_name VARCHAR(160),
    email VARCHAR(255),
    phone VARCHAR(40),
    address TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS shelves (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(40) NOT NULL UNIQUE,
    name VARCHAR(120) NOT NULL,
    location VARCHAR(160),
    description TEXT,
    device_id VARCHAR(100) UNIQUE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    barcode VARCHAR(100) UNIQUE,
    sku VARCHAR(80) UNIQUE,
    name VARCHAR(180) NOT NULL,
    brand VARCHAR(120),
    description TEXT,
    category_id BIGINT REFERENCES categories(id) ON DELETE SET NULL,
    supplier_id BIGINT REFERENCES suppliers(id) ON DELETE SET NULL,
    unit VARCHAR(30) NOT NULL DEFAULT 'piece',
    selling_price NUMERIC(12, 3) NOT NULL DEFAULT 0 CHECK (selling_price >= 0),
    purchase_price NUMERIC(12, 3) NOT NULL DEFAULT 0 CHECK (purchase_price >= 0),
    min_stock INTEGER NOT NULL DEFAULT 0 CHECK (min_stock >= 0),
    max_stock INTEGER CHECK (max_stock IS NULL OR max_stock >= min_stock),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS batches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES products(id) ON DELETE RESTRICT,
    batch_number VARCHAR(100) NOT NULL,
    expiration_date DATE NOT NULL,
    received_quantity INTEGER NOT NULL CHECK (received_quantity > 0),
    received_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    purchase_price NUMERIC(12, 3) CHECK (purchase_price IS NULL OR purchase_price >= 0),
    notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (product_id, batch_number)
);

CREATE TABLE IF NOT EXISTS batch_inventory (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id BIGINT NOT NULL REFERENCES batches(id) ON DELETE RESTRICT,
    shelf_id BIGINT NOT NULL REFERENCES shelves(id) ON DELETE RESTRICT,
    quantity INTEGER NOT NULL DEFAULT 0 CHECK (quantity >= 0),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (batch_id, shelf_id)
);

CREATE TABLE IF NOT EXISTS inventory_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES products(id) ON DELETE RESTRICT,
    batch_id BIGINT REFERENCES batches(id) ON DELETE RESTRICT,
    shelf_id BIGINT REFERENCES shelves(id) ON DELETE SET NULL,
    event_type VARCHAR(30) NOT NULL CHECK (
        event_type IN (
            'RESTOCK', 'SALE', 'REMOVAL', 'ADJUSTMENT',
            'EXPIRED', 'TRANSFER_IN', 'TRANSFER_OUT', 'SIMULATED'
        )
    ),
    quantity_change INTEGER NOT NULL CHECK (quantity_change <> 0),
    quantity_after INTEGER CHECK (quantity_after IS NULL OR quantity_after >= 0),
    source VARCHAR(30) NOT NULL DEFAULT 'MANUAL' CHECK (
        source IN ('MANUAL', 'BARCODE', 'MQTT', 'SIMULATOR', 'SYSTEM')
    ),
    reference_id VARCHAR(120),
    notes TEXT,
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS alerts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT REFERENCES products(id) ON DELETE CASCADE,
    batch_id BIGINT REFERENCES batches(id) ON DELETE CASCADE,
    shelf_id BIGINT REFERENCES shelves(id) ON DELETE SET NULL,
    alert_type VARCHAR(40) NOT NULL CHECK (
        alert_type IN (
            'LOW_STOCK', 'OUT_OF_STOCK', 'EXPIRING_SOON',
            'EXPIRED', 'ABNORMAL_STOCK_CHANGE'
        )
    ),
    priority VARCHAR(15) NOT NULL DEFAULT 'MEDIUM' CHECK (
        priority IN ('LOW', 'MEDIUM', 'HIGH', 'CRITICAL')
    ),
    title VARCHAR(180) NOT NULL,
    message TEXT NOT NULL,
    is_read BOOLEAN NOT NULL DEFAULT FALSE,
    is_resolved BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    resolved_at TIMESTAMPTZ
);

-- Query performance indexes
CREATE INDEX IF NOT EXISTS idx_products_category ON products(category_id);
CREATE INDEX IF NOT EXISTS idx_products_name ON products(name);
CREATE INDEX IF NOT EXISTS idx_batches_product ON batches(product_id);
CREATE INDEX IF NOT EXISTS idx_batches_expiration ON batches(expiration_date);
CREATE INDEX IF NOT EXISTS idx_batch_inventory_shelf ON batch_inventory(shelf_id);
CREATE INDEX IF NOT EXISTS idx_inventory_events_product_time
    ON inventory_events(product_id, occurred_at DESC);
CREATE INDEX IF NOT EXISTS idx_inventory_events_batch ON inventory_events(batch_id);
CREATE INDEX IF NOT EXISTS idx_alerts_status_time
    ON alerts(is_resolved, is_read, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_alerts_type ON alerts(alert_type);

-- Automatically maintain products.updated_at when a product is changed.
CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_products_updated_at ON products;
CREATE TRIGGER trg_products_updated_at
BEFORE UPDATE ON products
FOR EACH ROW EXECUTE FUNCTION set_updated_at();

DROP TRIGGER IF EXISTS trg_batch_inventory_updated_at ON batch_inventory;
CREATE TRIGGER trg_batch_inventory_updated_at
BEFORE UPDATE ON batch_inventory
FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- Useful read-only views: current product stock and batch expiry status.
CREATE OR REPLACE VIEW product_stock AS
SELECT
    p.id AS product_id,
    p.name AS product_name,
    p.barcode,
    p.min_stock,
    COALESCE(SUM(bi.quantity), 0)::BIGINT AS total_quantity,
    CASE
        WHEN COALESCE(SUM(bi.quantity), 0) = 0 THEN 'OUT_OF_STOCK'
        WHEN COALESCE(SUM(bi.quantity), 0) <= p.min_stock THEN 'LOW_STOCK'
        ELSE 'IN_STOCK'
    END AS stock_status
FROM products p
LEFT JOIN batches b ON b.product_id = p.id
LEFT JOIN batch_inventory bi ON bi.batch_id = b.id
GROUP BY p.id, p.name, p.barcode, p.min_stock;

CREATE OR REPLACE VIEW batch_expiry_status AS
SELECT
    b.id AS batch_id,
    b.product_id,
    p.name AS product_name,
    b.batch_number,
    b.expiration_date,
    COALESCE(SUM(bi.quantity), 0)::BIGINT AS remaining_quantity,
    (b.expiration_date - CURRENT_DATE) AS days_remaining,
    CASE
        WHEN b.expiration_date < CURRENT_DATE THEN 'EXPIRED'
        WHEN b.expiration_date = CURRENT_DATE THEN 'EXPIRES_TODAY'
        WHEN b.expiration_date <= CURRENT_DATE + 7 THEN 'EXPIRING_SOON'
        ELSE 'VALID'
    END AS expiry_status
FROM batches b
JOIN products p ON p.id = b.product_id
LEFT JOIN batch_inventory bi ON bi.batch_id = b.id
GROUP BY b.id, b.product_id, p.name, b.batch_number, b.expiration_date;

COMMIT;
